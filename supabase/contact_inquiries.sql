-- Run in Supabase Dashboard > SQL Editor.
create table if not exists public.contact_inquiries (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  email text not null check (char_length(email) between 3 and 254),
  category text not null check (char_length(category) between 1 and 100),
  message text not null check (char_length(message) between 1 and 10000),
  created_at timestamptz not null default now()
);

alter table public.contact_inquiries enable row level security;

-- Public visitors may INSERT only. No public SELECT/UPDATE/DELETE.
revoke all on table public.contact_inquiries from anon, authenticated;
grant insert (name, email, category, message) on table public.contact_inquiries to anon;

drop policy if exists "Public can submit contact inquiries" on public.contact_inquiries;
create policy "Public can submit contact inquiries"
on public.contact_inquiries
for insert
to anon
with check (
  char_length(name) between 1 and 100
  and char_length(email) between 3 and 254
  and char_length(category) between 1 and 100
  and char_length(message) between 1 and 10000
);
