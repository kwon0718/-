create table if not exists public.site_comments (
  id bigint generated by default as identity primary key,
  message text not null check (char_length(trim(message)) between 1 and 1000),
  created_at timestamptz not null default now()
);

alter table public.site_comments enable row level security;

-- 방문자는 댓글 목록 조회와 새 댓글 등록만 가능
revoke all on table public.site_comments from anon, authenticated;
grant select, insert on table public.site_comments to anon, authenticated;

drop policy if exists "Anyone can read site comments" on public.site_comments;
create policy "Anyone can read site comments"
on public.site_comments for select
to anon, authenticated
using (true);

drop policy if exists "Anyone can add site comments" on public.site_comments;
create policy "Anyone can add site comments"
on public.site_comments for insert
to anon, authenticated
with check (char_length(trim(message)) between 1 and 1000);
